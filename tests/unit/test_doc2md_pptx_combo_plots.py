from io import BytesIO
from zipfile import ZipFile

import pytest
from lxml import html
from pptx import Presentation
from pptx.chart.data import CategoryChartData
from pptx.enum.chart import XL_CHART_TYPE
from pptx.oxml import parse_xml
from pptx.util import Inches
from xlsxwriter import Workbook

from paddleocr import doc2md_convert


def _insert_combo_plot_area(chart):
    # python-pptx reads combination charts but cannot create them. Use the
    # plot area and source data workbook generated by XlsxWriter together.
    with BytesIO() as stream:
        with Workbook(stream) as workbook:
            data = workbook.add_worksheet("Data")
            data.write_column("A1", ["January", "February"])
            data.write_column("B1", [10, 20])
            data.write_column("C1", ["February", "January", "March"])
            data.write_column("D1", [100, 200, 300])
            columns = workbook.add_chart({"type": "column"})
            columns.add_series(
                {"categories": "=Data!$A$1:$A$2", "values": "=Data!$B$1:$B$2"}
            )
            columns.set_x_axis({"name": "Month"})
            columns.set_y_axis({"name": "Orders"})
            line = workbook.add_chart({"type": "line"})
            line.add_series(
                {
                    "categories": "=Data!$C$1:$C$3",
                    "values": "=Data!$D$1:$D$3",
                    "y2_axis": True,
                }
            )
            line.set_x2_axis({"name": "Revenue month", "visible": True})
            line.set_y2_axis({"name": "Revenue"})
            columns.combine(line)
            data.insert_chart("F1", columns)

        with ZipFile(stream) as archive:
            combo = parse_xml(archive.read("xl/charts/chart1.xml")).chart
        primary = set(combo.plotArea.xpath("c:barChart/c:axId/@val"))
        secondary = set(combo.plotArea.xpath("c:lineChart/c:axId/@val"))
        assert len(primary) == len(secondary) == 2 and primary.isdisjoint(secondary)
        chart_xml = chart._element.chart
        chart_xml.replace(chart_xml.plotArea, combo.plotArea)
        chart.part.chart_workbook.update_from_xlsx_blob(stream.getvalue())


@pytest.mark.parametrize("combo", [False, True], ids=["single", "combination"])
def test_pptx_exports_all_chart_plots(tmp_path, combo):
    presentation = Presentation()
    slide = presentation.slides.add_slide(presentation.slide_layouts[6])
    data = CategoryChartData()
    data.categories = ["January", "February"]
    data.add_series("Orders", [10, 20])
    chart = slide.shapes.add_chart(
        XL_CHART_TYPE.COLUMN_CLUSTERED, 0, 0, Inches(6), Inches(4), data
    ).chart
    chart.chart_title.text_frame.text = "Monthly report"
    if combo:
        _insert_combo_plot_area(chart)
    path = tmp_path / "chart.pptx"
    presentation.save(str(path))

    document = html.fragment_fromstring(
        doc2md_convert(str(path)).markdown, create_parent=True
    )
    tables = document.findall("table")
    rows = [
        [row.xpath("./td/text()") for row in table.findall("./tbody/tr")]
        for table in tables
    ]
    expected = [[["January", "10.0"], ["February", "20.0"]]]
    if combo:
        expected.append(
            [["February", "100.0"], ["January", "200.0"], ["March", "300.0"]]
        )
    assert rows == expected
    assert document.xpath(".//caption/text()") == ["Monthly report"]
    if combo:
        assert tables[0].xpath("./thead/tr/th/text()") == ["Month", "Orders"]
        assert tables[1].xpath("./thead/tr/th/text()") == ["Revenue month", "Revenue"]
